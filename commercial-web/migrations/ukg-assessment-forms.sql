insert into public.literacy_phonics_items(code,family,grapheme,phoneme,example_word,teaching_note,sequence)
select 'ukg-form-'||e.form||'-'||i.code,i.family,i.grapheme,i.phoneme,e.word,'Assessment form '||upper(e.form),i.sequence + case when e.form='b' then 2000 else 4000 end
from examples e join public.literacy_phonics_items i on i.code=e.source
on conflict(code) do nothing;
insert into public.literacy_competency_phonics_items(competency_id,item_id)
select m.competency_id,n.id from public.literacy_phonics_items n join public.literacy_phonics_items original on original.code=substring(n.code from 12)
join public.literacy_competency_phonics_items m on m.item_id=original.id
join public.literacy_competencies c on c.id=m.competency_id and c.code in ('UKG001','UKG002','UKG008')
where n.code like 'ukg-form-b-%' or n.code like 'ukg-form-c-%'
on conflict do nothing;
